# norm范数
# 生成一个 1000 维(这里的维指的是列) 的随机向量(1,1000)，值在 [-1, 1] 之间      # 无论多少维,列，行,一个矩阵始终都只是在表示一个点,只是数字多了些
x = np.random.uniform(-1, 1, 1000)

# 计算欧几里得范数 (L2 范数)              # 从原点到该数组的直线距离
l2_norm = np.linalg.norm(x, ord=2)     # 这个数值的大小反映了向量的整体能量（大小），通常比L1范数小，但比L∞范数大

# 计算 1-范数 (L1 范数)                  # 所有元素的绝对值相加,反映了向量所有分量的总幅度
l1_norm = np.linalg.norm(x, ord=1)     # ord 表示当前向量的阶数,用于指定计算哪种范数

# 计算无穷范数 (L∞ 范数)                 # 数组中最大的那个绝对值,反映了向量中最大数值的影响力
inf_norm = np.linalg.norm(x, ord=np.inf)

# ':.4f' 代表 保留 4 位小数，确保结果格式美观。
print(f"欧几里得范数 (L2): {l2_norm:.4f}")            # 欧几里得范数 (L2): 18.5227
print(f"1-范数 (L1): {l1_norm:.4f}")                 # 1-范数 (L1): 510.5341
print(f"无穷范数 (L∞): {inf_norm:.4f}")               # 无穷范数 (L∞): 0.9991

