# 行列式（Determinant）
# 行列式是一个标量,表示矩阵的“大小”或“扩展比例”,在 判断矩阵是否可逆 时很重要：
# det(A) != 0 → 矩阵可逆
# det(A) = 0 → 矩阵不可逆（奇异矩阵）
A = np.array([[1, 2],
              [3, 4]])
det_A = np.linalg.det(A)  # det计算行列式

# 计算过程:det(A)=1×4−2×3=−2    # 主对角线乘积 - 副对角线乘积
print("A 的行列式:", det_A)    # A 的行列式:-2  # det不为零,矩阵可逆
B = np.array([[2, 4],
              [1, 2]])  # 行列式 = 2×2 - 4×1 = 0
det_B = np.linalg.det(B)
print("B 的行列式:", det_B)    # B 的行列式: 0.0       # 行列式为 0（矩阵不可逆）

# 特征值 & 特征向量（Eigenvalues & Eigenvectors）
