# 小知识：python中的浮点型约算使用"银行家舍入法"(又称“偶数舍入”),而不是“四舍五入”或看起来很像的“五舍六入”
# 当尾数刚好是 0.5 时，会靠近最近的“偶数”。
print("%.1f" % 2.5)     # → 2.0（不是 3.0！）
print("%.1f" % 3.5)     # → 4.0（这个才进了！）
# 2.5：离 2 和 3 一样远，但 2 是偶数，所以保留 2.0
# 3.5：离 3 和 4 一样远，但 4 是偶数，所以保留 4.0
