# 字符串格式化：
# %格式（土土的C风格）
print("我是:%s" % "bai")                                       # 我是:bai                               %s：字符串(自动调用 str())
print("单字符:%c 与 int转码:%c" % ('A',66))                    # 单字符:A 与 int转码:B                  %c:单个字符(传入字符或ASCII码)
print("今年刚满%d岁" % 18)                                     # 今年刚满18岁                           %d:十进制整数(int)
print("对象是：%r" % "hei")                                    # 对象是：'hei'                          %r:原始字符串（调用 repr()）
print("编号:%i" % 17.9)                                        # 编号:17                               %i:同 %d，但更宽容(可自动转换为 int)
print("分数:%f" % 88.5)                                        # 分数:88.500000                        %f:浮点数（默认保留6位小数）
print("分数:%.2f" % 88.506)                                    # 分数:88.51                            %.2f:浮点数（银行家舍入法，指定保留2位）
print("%e 与 %E" % (1000,1000))                                # 1.000000e+03 与 1.000000E+03          %e/%E:科学计数法(小写/大写E)
print("%o" % 8)                                                # 10                                    %o:八进制(octal)
print("%x 与 %X" % (10,17))                                    # a 与 11                               %x/%X:十六进制（小写/大写）



# .format()(中生代，几乎没见过)
print("我的名字是 {}, 年龄是 {}".format("bai", 18))                             # 我的名字是 bai, 年龄是 18
# {} 是占位符，format() 里面的值会自动填进去（按照顺序）

print("我的名字是 {0}, 今年刚满 {1} 。再次重申，我叫 {0}".format("bai",18))        # 我的名字是 bai, 今年刚满 18 。再次重申，我叫 bai
# 带索引，重复利用

print("我的名字是 {name}, 年龄是 {age}".format(age=18,name='bai'))                    # 我的名字是 bai, 年龄是 18
# 带关键词传参，这样就可以顺序无关，按名字插值


# 指定格式：可实现 % 的操作。 {:} 是格式说明符，可以在后面接入.2f,c这类。所以嘛，%格式化还是可以了解一二的
pi = 3.1415926
print("圆周率大约是 {:.2f}".format(pi))                                              # 圆周率大约是 3.14
print("65指向的编码是 {:c}".format(65))                                              # A



# 好了，压轴的超级新生代 f！直接关键词传参，太简洁啦
name = 'bai'
age = 18

print(f"我的名字是{name},今年{age}岁，身高{111.116:.2f}")                               # 我的名字是bai,今年18岁，身高111.12
# 结合了以上的两种格式化方法，只要在开头打个f格式化符，后面的{}就都能写入


