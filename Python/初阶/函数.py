# 函数特性

# 一、可以赋值给变量
def de1(x):
    return x-1

d = de1                          # 别加() , 那是调用        
print(d(2))                      # 1                               # 此时d = de1 ，d(2) = de1(2) = 2-1


# 二、可以作为参数传入另一个函数
def de1(x):
    return x-1
def de2(x,de):
    return de(x) - 1
    
print(de2(3,de1))                # 1


# 三、可以在其他函数中直接调用另一个函数(函数嵌套，注意上下顺序，不能在过去调用未来)
def de1(x):
    print(x)                     # 3           
    return x-1                   # return 语句只终止当前函数，不影响外部函数继续执行
def de2(x):
    x = de1(x)                
    print(x)                     # 2
    return x - 1
    
print(de2(3))                    # 1


# 四、可以调用自身(即递归，现在调用现在)
def fact(n):
    if n == 1:return 1           # 必须要有终止条件(递归出口)，不然函数无法停止，无限深度
    return n*fact(n-1)           # 参数也要动，不然无法靠近终止条件(这里也有漏洞，如果输入的形参本身就小于1，那么也会无限-1递归，按情况增加保护)

print(fact(5))                   # 120       # 5*4*3*2*1 = 120


# 五、闭包
def outer(x):
    def inner(y):
        return x + y
    return inner               # 返回内函数，但没有执行
    
f = outer(5)                   # 返回的是 inner 函数，并且记住了 x=5
print(f(3))                    # 输出 8，其实就是 5 + 3



