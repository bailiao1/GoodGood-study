# 小扩展

# global：修改全局变量(告诉函数，不需要创建新变量，直接去全局里找)
def de():                      # 不需要传参就不要定义形参
    global x                   # global声明，让函数直接去全局里找 x
    x -= 1                     # 还是需要接收这个新值，不能直接 x-1 丢在那 
    
x = 2                          # 先定义一个全局变量
de()                           # 调用函数
print(x)                       # 输出 1 ， x被修改了


